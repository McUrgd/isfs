<#
.SYNOPSIS
    Tags a version, pushes it and publishes the GitHub release.

.DESCRIPTION
    The manual release procedure in one command:

        1. checks that the release is made from a clean main that matches
           origin/main, and that the tag does not exist yet;
        2. bumps the "proof of concept (vX.Y)" marker of README.md when it
           points at an older minor version, and commits the change;
        3. creates the annotated tag vX.Y.Z and pushes the branch and the tag;
        4. publishes the GitHub release with notes generated by GitHub from the
           commits since the previous tag, or with the text of -NotesFile.

    The release is created through the GitHub API with the credentials git
    already uses for origin: GITHUB_TOKEN when it is set, otherwise the
    password returned by "git credential fill". The token is never printed and
    never written to disk.

.PARAMETER Version
    Version to release, without the leading "v": 0.2.0.

.PARAMETER NotesFile
    Markdown file with the release notes. Default: GitHub generates them.

.PARAMETER Prerelease
    Mark the release as a pre-release.

.PARAMETER DryRun
    Print what would be done and change nothing.

.PARAMETER NoPush
    Create the tag locally and stop; the release is skipped.

.PARAMETER NoRelease
    Push the branch and the tag, but do not create the GitHub release.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\release.ps1 0.2.0 -DryRun

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\release.ps1 0.2.0 -NotesFile notes.md
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string] $Version,

    [string] $NotesFile = '',

    [switch] $Prerelease,
    [switch] $DryRun,
    [switch] $NoPush,
    [switch] $NoRelease
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$tag = "v$Version"
$minor = (($Version -split '\.')[0..1]) -join '.'

function Write-Step([string] $Text)
{
    Write-Host "==> $Text"
}

function Invoke-Git
{
    param([string[]] $Arguments)

    & git @Arguments
    if ($LASTEXITCODE)
    {
        throw "git $($Arguments -join ' ') failed with exit code $LASTEXITCODE"
    }
}

Push-Location $root
try
{
    if (-not (Get-Command git -ErrorAction SilentlyContinue))
    {
        throw 'git is not on PATH'
    }

    # ---- 1. Preconditions -------------------------------------------------
    $branch = (& git rev-parse --abbrev-ref HEAD).Trim()
    if ($branch -ne 'main')
    {
        throw "a release is made from 'main', not from '$branch'"
    }

    $dirty = @(& git status --porcelain)
    if ($dirty.Count)
    {
        throw "the working tree is not clean:`n$($dirty -join "`n")"
    }

    & git fetch --quiet origin
    if ($LASTEXITCODE)
    {
        throw 'git fetch origin failed'
    }

    $head = (& git rev-parse HEAD).Trim()
    $upstream = (& git rev-parse 'origin/main' 2>$null).Trim()
    if (-not $upstream)
    {
        throw 'origin/main does not exist; push the branch first'
    }
    if ($head -ne $upstream)
    {
        throw 'main and origin/main differ; push or pull before releasing'
    }

    $localTag = & git rev-parse -q --verify "refs/tags/$tag" 2>$null
    if ($LASTEXITCODE -eq 0 -and $localTag)
    {
        throw "tag $tag already exists"
    }
    $remoteTag = @(& git ls-remote --tags origin "refs/tags/$tag" 2>$null)
    if ($remoteTag.Count)
    {
        throw "tag $tag already exists on origin"
    }

    Write-Step "releasing $tag from $($head.Substring(0, 7)) on main"

    # ---- 2. README version marker -----------------------------------------
    $readme = Join-Path $root 'README.md'
    $marker = 'proof of concept \(v(\d+\.\d+)\)'
    $text = [IO.File]::ReadAllText($readme)
    $match = [regex]::Match($text, $marker)
    $readmeChanged = $false

    if (-not $match.Success)
    {
        Write-Warning "README.md has no 'proof of concept (vX.Y)' marker; the version is not bumped"
    }
    elseif ($match.Groups[1].Value -eq $minor)
    {
        Write-Step "README.md already says v$minor"
    }
    else
    {
        $readmeChanged = $true
        Write-Step "README.md: v$($match.Groups[1].Value) -> v$minor"
        if (-not $DryRun)
        {
            $updated = [regex]::Replace($text, $marker, "proof of concept (v$minor)")
            [IO.File]::WriteAllText($readme, $updated, (New-Object Text.UTF8Encoding($false)))
        }
    }

    # ---- 3. Notes ---------------------------------------------------------
    $notes = ''
    if ($NotesFile)
    {
        if (-not (Test-Path -LiteralPath $NotesFile))
        {
            throw "notes file '$NotesFile' not found"
        }
        $notes = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $NotesFile).Path).Trim()
    }

    # ---- 4. Commit, tag, push ---------------------------------------------
    if ($readmeChanged -and -not $DryRun)
    {
        Invoke-Git @('add', 'README.md')
        Invoke-Git @('commit', '-m', "docs: bump the version to $minor")
    }

    $tagArgs = @('tag', '-a', $tag, '-m', "ISFS $Version")
    if ($notes)
    {
        $tagArgs += @('-m', $notes)
    }

    if ($DryRun)
    {
        Write-Step "would run: git $($tagArgs -join ' ')"
        if ($readmeChanged)
        {
            Write-Step 'would push: main'
        }
        if ($NoPush)
        {
            Write-Step 'NoPush: the tag would stay local'
        }
        else
        {
            Write-Step "would push: $tag"
            if ($NoRelease)
            {
                Write-Step 'NoRelease: no GitHub release'
            }
            else
            {
                $source = if ($notes) { "the text of $NotesFile" } else { 'notes generated by GitHub' }
                Write-Step "would publish the GitHub release $tag with $source"
            }
        }
        return
    }

    Invoke-Git $tagArgs
    Write-Step "tagged $tag"

    if ($NoPush)
    {
        Write-Step 'NoPush: the branch and the tag stay local'
        return
    }

    if ($readmeChanged)
    {
        Invoke-Git @('push', 'origin', 'HEAD:main')
        Write-Step 'pushed main'
    }
    Invoke-Git @('push', 'origin', "refs/tags/$tag")
    Write-Step "pushed $tag"

    if ($NoRelease)
    {
        Write-Step 'NoRelease: no GitHub release was created'
        return
    }

    # ---- 5. GitHub release ------------------------------------------------
    $remote = (& git remote get-url origin).Trim()
    if ($remote -notmatch 'github\.com[:/](?<owner>[^/]+)/(?<repo>[^/]+?)(\.git)?$')
    {
        throw "origin '$remote' is not a GitHub remote; create the release manually"
    }
    $slug = "$($Matches.owner)/$($Matches.repo)"

    $token = $env:GITHUB_TOKEN
    if (-not $token)
    {
        # The same credential that git uses for origin. Not printed, not saved.
        $savedPrompt = $env:GIT_TERMINAL_PROMPT
        $env:GIT_TERMINAL_PROMPT = '0'
        try
        {
            $credential = "protocol=https`nhost=github.com`n`n" | & git credential fill 2>$null
            $token = ($credential | Where-Object { $_ -match '^password=' }) -replace '^password=', ''
        }
        finally
        {
            $env:GIT_TERMINAL_PROMPT = $savedPrompt
        }
    }
    if (-not $token)
    {
        throw "no GitHub credentials: set GITHUB_TOKEN, or push once so that the credential helper stores them"
    }

    $payload = @{
        tag_name   = $tag
        name       = "ISFS $Version"
        draft      = $false
        prerelease = [bool]$Prerelease
    }
    if ($notes)
    {
        $payload.body = $notes
    }
    else
    {
        $payload.generate_release_notes = $true
    }

    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    try
    {
        $release = Invoke-RestMethod -Method Post -Uri "https://api.github.com/repos/$slug/releases" `
            -Headers @{
                Authorization = "Bearer $token"
                Accept        = 'application/vnd.github+json'
                'User-Agent'  = 'isfs-release'
            } `
            -Body ([Text.Encoding]::UTF8.GetBytes(($payload | ConvertTo-Json -Depth 4))) `
            -ContentType 'application/json; charset=utf-8'
    }
    catch
    {
        Write-Warning "the tag $tag is pushed, but the release was not created: $($_.Exception.Message)"
        Write-Warning "create it manually at https://github.com/$slug/releases/new?tag=$tag"
        exit 1
    }

    Write-Host ''
    Write-Step "release: $($release.html_url)"
}
finally
{
    Pop-Location
}
